#!/usr/bin/env node
/** Sync web/.env.local from bot root .env — run: node scripts/sync-env.mjs */
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.join(__dirname, '..');
const botEnvPath = path.join(webDir, '..', '.env');
const outPath = path.join(webDir, '.env.local');

function parseEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/);
    if (m) out[m[1]] = m[2].trim();
  }
  return out;
}

const bot = parseEnv(botEnvPath);
const existing = parseEnv(outPath);

const discordClientId = '1188001834305060925';
const supabaseUrl = bot.SUPABASE_URL || existing.SUPABASE_URL;
const serviceKey = bot.SUPABASE_SERVICE_ROLE_KEY || existing.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !serviceKey) {
  console.error('Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in ../.env');
  process.exit(1);
}

const sessionSecret = existing.SESSION_SECRET || crypto.randomBytes(32).toString('hex');
const discordSecret = existing.DISCORD_CLIENT_SECRET && !existing.DISCORD_CLIENT_SECRET.includes('your_')
  ? existing.DISCORD_CLIENT_SECRET
  : '';

const appUrl = (
  bot.APP_URL ||
  bot.NEXT_PUBLIC_APP_URL ||
  bot.PUBLIC_APP_URL ||
  existing.NEXT_PUBLIC_APP_URL ||
  'https://deelo.nikkithewikki.top'
).replace(/\/$/, '');

const botToken = bot.DISCORD_BOT_TOKEN || bot.DISCORD_TOKEN || existing.DISCORD_BOT_TOKEN || existing.DISCORD_TOKEN || '';

const lines = [
  '# Auto-generated by scripts/sync-env.mjs — edit DISCORD_CLIENT_SECRET manually',
  `NEXT_PUBLIC_APP_URL=${appUrl}`,
  `NEXT_PUBLIC_DISCORD_CLIENT_ID=${discordClientId}`,
  `NEXT_PUBLIC_SUPABASE_URL=${supabaseUrl}`,
  `# Anon key optional — admin auth uses service role server-side`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${existing.NEXT_PUBLIC_SUPABASE_ANON_KEY || 'not-required-for-dashboard'}`,
  '',
  `DISCORD_CLIENT_ID=${discordClientId}`,
  discordSecret ? `DISCORD_CLIENT_SECRET=${discordSecret}` : 'DISCORD_CLIENT_SECRET=',
  botToken ? `DISCORD_BOT_TOKEN=${botToken}` : 'DISCORD_BOT_TOKEN=',
  botToken ? `DISCORD_TOKEN=${botToken}` : 'DISCORD_TOKEN=',
  `SUPABASE_URL=${supabaseUrl}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
  `SESSION_SECRET=${sessionSecret}`,
  '',
];

fs.writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${outPath}`);
if (!discordSecret) {
  console.log('⚠️  Set DISCORD_CLIENT_SECRET in web/.env.local for Discord dashboard login');
}
if (!botToken) {
  console.log('⚠️  Set DISCORD_TOKEN in ../.env (or DISCORD_BOT_TOKEN here) so the dashboard can post ticket panels & role buttons to Discord');
}
